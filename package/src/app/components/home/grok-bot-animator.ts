const BLINK_MS = 120;

function bez(ease: number[] | null | undefined, t: number): number {
  if (!ease || ease.length < 4) return t;
  const x1 = ease[0], y1 = ease[1], x2 = ease[2], y2 = ease[3];
  let u = t;
  for (let i = 0; i < 8; i++) {
    const x = 3 * (1 - u) * (1 - u) * u * x1 + 3 * (1 - u) * u * u * x2 + u * u * u;
    const dx = 3 * (1 - u) * (1 - u) * x1 + 6 * (1 - u) * u * (x2 - x1) + 3 * u * u * (1 - x2);
    if (Math.abs(dx) < 1e-6) break;
    u -= (x - t) / dx;
    if (u < 0) { u = 0; break; }
    if (u > 1) { u = 1; break; }
  }
  return 3 * (1 - u) * (1 - u) * u * y1 + 3 * (1 - u) * u * u * y2 + u * u * u;
}

function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t;
}

function lerpV(a: any, b: any, t: number): any {
  if (typeof a === "number") return lerp(a, b, t);
  if (Array.isArray(a)) return a.map((v, i) => lerp(v, b[i] ?? v, t));
  return b;
}

function sampleTrack(keys: any[] | null | undefined, time: number): any {
  if (!keys || !keys.length) return null;
  if (time <= keys[0].t) return keys[0].v;
  for (let i = 0; i < keys.length - 1; i++) {
    const a = keys[i], b = keys[i + 1];
    if (time >= a.t && time <= b.t) {
      const span = Math.max(1e-6, b.t - a.t);
      const u = bez(a.ease, (time - a.t) / span);
      return lerpV(a.v, b.v, u);
    }
  }
  return keys[keys.length - 1].v;
}

function officialSequence(index: number): { state: string; ms: number }[] {
  const n = SEQS[index % SEQS.length];
  const r = index % n.length;
  const a = 0.82 + ((7 * index) % 6) * 0.07;
  return n.slice(r).concat(n.slice(0, r)).map((s) => ({ state: s.state, ms: Math.round(s.ms * a) }));
}

function stateAt(seq: { state: string; ms: number }[], tms: number): { state: string; localMs: number; stepMs: number } {
  const total = seq.reduce((s, x) => s + x.ms, 0);
  let t = ((tms % total) + total) % total;
  for (const step of seq) {
    if (t < step.ms) return { state: step.state, localMs: t, stepMs: step.ms };
    t -= step.ms;
  }
  return { state: seq[0].state, localMs: 0, stepMs: seq[0].ms };
}

function clipForState(state: string, localSec: number, botIndex: number): { clip: any; name: string; t: number } {
  const names = STATE_CLIPS[state] || IDLE_CLIPS;
  if (state === "idle") {
    let t = localSec, i = 0;
    while (true) {
      const name = names[i % names.length];
      const clip = CLIPS[name];
      const dur = clip ? clip.duration : 4;
      if (t < dur) return { clip, name, t };
      t -= dur;
      i++;
      if (i > 20) return { clip, name, t: 0 };
    }
  } else {
    const name = names[0];
    const clip = CLIPS[name];
    const dur = clip ? clip.duration : 4;
    let t = localSec;
    if (t > dur) t = dur;
    t = t % dur;
    return { clip, name, t };
  }
}

function blinkAmount(clip: any, t: number): number {
  if (!clip || !clip.tracks || !clip.tracks.expression) return 0;
  const keys = clip.tracks.expression;
  let amt = 0;
  for (const k of keys) {
    if (k.v === "blink") {
      const dt = Math.abs(t - k.t);
      const half = BLINK_MS / 1000;
      if (dt < half) amt = Math.max(amt, 1 - dt / half);
    }
  }
  return amt;
}

export interface AnimatedBotRegistration {
  container: HTMLElement;
  svg: SVGSVGElement;
  eyes: SVGPathElement[];
  index: number;
}

const activeBots = new Set<AnimatedBotRegistration>();
let rafId: number | null = null;
let startTime: number = 0;

function tick() {
  if (typeof window === "undefined") return;
  const now = performance.now() - startTime;

  for (const bot of activeBots) {
    if (!bot.svg.isConnected) {
      activeBots.delete(bot);
      continue;
    }

    const idx = bot.index;
    const seq = officialSequence(idx);
    const st = stateAt(seq, now);
    const { clip, t } = clipForState(st.state, st.localMs / 1000, idx);

    const pos = (clip && sampleTrack(clip.tracks.position, t)) || [0, 0];
    const rot = (clip && sampleTrack(clip.tracks.rotation, t)) || [0, 0, 0];
    const clipBlink = blinkAmount(clip, t);

    // Subtle organic buoyancy and sway so bots are always vividly alive
    const organicBob = Math.sin((now * 0.0024) + (idx * 0.95)) * 6; // ±6% float
    const organicTilt = Math.sin((now * 0.0018) + (idx * 1.25)) * 4.5; // ±4.5deg tilt

    // Official translation in percent and rotation in degrees
    const tx = (pos[0] || 0) * 45;
    const ty = -(pos[1] || 0) * 45 + organicBob;
    const rz = (rot[2] || 0) + organicTilt;
    const yaw = rot[1] || 0;
    const pitch = rot[0] || 0;

    const transformValue = `translate3d(${tx.toFixed(2)}%, ${ty.toFixed(2)}%, 0) rotate(${rz.toFixed(2)}deg)`;
    if (bot.container) {
      bot.container.style.transformOrigin = "50% 50%";
      bot.container.style.transform = transformValue;
      bot.container.style.willChange = "transform";
    }
    if (bot.svg) {
      bot.svg.style.transformOrigin = "50% 50%";
      bot.svg.style.transform = transformValue;
    }

    // Periodic natural blink every ~3.4s layered with clip blinks
    const cycle = (now + idx * 720) % 3400;
    let natBlink = 0;
    if (cycle < 160) {
      natBlink = Math.sin((cycle / 160) * Math.PI);
    }
    const finalBlink = Math.max(clipBlink, natBlink);
    const sy = Math.max(0.06, 1 - 0.94 * finalBlink);

    const ex = yaw * 0.32 + Math.sin((now * 0.0016) + (idx * 1.3)) * 2.5;
    const ey = -pitch * 0.25 + Math.cos((now * 0.0013) + (idx * 1.1)) * 2.0;

    const eyes =
      bot.eyes.length > 0
        ? bot.eyes
        : Array.from(bot.svg.querySelectorAll<SVGPathElement>(".grok-bot-mark__eye"));

    for (const eye of eyes) {
      if (eye && eye.isConnected) {
        eye.style.transformBox = "fill-box";
        eye.style.transformOrigin = "50% 50%";
        eye.style.transform = `translate(${ex.toFixed(2)}px, ${ey.toFixed(2)}px) scaleY(${sy.toFixed(3)})`;
      }
    }
  }

  if (activeBots.size > 0) {
    rafId = requestAnimationFrame(tick);
  } else {
    rafId = null;
  }
}

export function registerAnimatedBot(
  container: HTMLElement,
  svg: SVGSVGElement,
  eyes: SVGPathElement[],
  index: number
): () => void {
  if (typeof window === "undefined") return () => {};
  if (!startTime) startTime = performance.now();

  const item: AnimatedBotRegistration = { container, svg, eyes, index };
  activeBots.add(item);

  if (rafId === null) {
    rafId = requestAnimationFrame(tick);
  }

  return () => {
    activeBots.delete(item);
    if (activeBots.size === 0 && rafId !== null) {
      cancelAnimationFrame(rafId);
      rafId = null;
    }
  };
}
